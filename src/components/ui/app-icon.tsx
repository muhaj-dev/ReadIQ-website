export type AppIconName = keyof typeof ICONS;

type Props = {
  name: AppIconName;
  /** Pixel size (width = height). Defaults to 24, like the mobile app. */
  size?: number;
  /** Fill the glyph — the mobile app's "filled" Material variant. */
  filled?: boolean;
  className?: string;
  strokeWidth?: number;
  'aria-label'?: string;
};

/** Colour comes from `className` (e.g. text-rq-primary) — the icon uses currentColor. */
export function AppIcon({ name, size = 24, filled = false, className, strokeWidth = 2, ...rest }: Props) {
  const Icon = ICONS[name];
  return (
    <Icon
      width={size}
      height={size}
      strokeWidth={strokeWidth}
      className={cn('shrink-0', filled && 'fill-current', className)}
      aria-hidden={rest['aria-label'] ? undefined : true}
      aria-label={rest['aria-label']}
    />
  );
}
